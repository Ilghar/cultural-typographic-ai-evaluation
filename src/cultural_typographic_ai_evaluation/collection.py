"""M05 collection (bridged cases + specs + generated corruption suite) and M06 detector baseline."""
import hashlib, json, pathlib
from collections import Counter, defaultdict
from .bridge import bridge
from .schema import load_schema, validate
from .slice import render_card, evaluate
from .checks import diagram_fidelity
def mermaid(stages, swap=None, drop=None, add_metric=False):
    st = list(stages)
    if swap: st[swap[0]], st[swap[1]] = st[swap[1]], st[swap[0]]
    if drop is not None: st.pop(drop)
    lines = ["flowchart LR"] + [f'  N{i}["{s}"]' + (f" --> N{i+1}" if i + 1 < len(st) else "") for i, s in enumerate(st)]
    if add_metric: lines.append('  N0 -.- M["accuracy 94%"]')
    return "\n".join(lines)
CORRUPTIONS = {  # name -> (constraint type it should break, transform on fields)
    "drop_zwnj": ("glyph_exact", lambda f: {**f, "title": f["title"].replace("\u200c", "")}),
    "zwnj_to_space": ("glyph_exact", lambda f: {**f, "title": f["title"].replace("\u200c", " ")}),
    "arabic_kaf": ("glyph_exact", lambda f: {**f, "title": f["title"].replace("\u06a9", "\u0643")}),
    "arabic_yeh": ("glyph_exact", lambda f: {**f, "title": f["title"].replace("\u06cc", "\u064a")}),
    "drop_venue": ("required_fields", lambda f: {**f, "venue": ""}),
}
def build(root):
    root = pathlib.Path(root); cdir = root / "data/collection_v1"
    specs = json.loads((cdir / "specs.json").read_text(encoding="utf-8"))["specs"]
    cases = bridge(json.loads((root / "inputs/synthetic_cases.json").read_text(encoding="utf-8")), specs)
    s = load_schema(root, "case.schema.json")
    return {"collection": "cultural-typographic-cases", "version": "1.0.0", "empirical_items": 0, "split": "all dev (n=6 too small to split)",
            "files": {n: hashlib.sha256((p).read_bytes()).hexdigest() for n, p in [("inputs/synthetic_cases.json", root / "inputs/synthetic_cases.json"), ("data/collection_v1/specs.json", cdir / "specs.json")]},
            "cases": cases, "automatable": {c["id"]: [k["type"] for k in c["constraints"] if "expected" in k] for c in cases},
            "human_only": {c["id"]: [k["type"] for k in c["constraints"] if "expected" not in k] for c in cases},
            "errors": [f"{c['id']}: {e}" for c in cases for e in validate(c, s)]}, specs
def corruption_suite(specs):
    """Measured detector baseline: does each automated check flag each applicable corruption, and stay quiet on clean?"""
    rows = []
    for cid, sp in sorted(specs.items()):
        if "fields" in sp:
            clean = evaluate(sp, render_card(sp)); rows.append({"case": cid, "variant": "clean", "should_fail": [], "failed": sorted(r["constraint_id"] for r in clean if r["verdict"] == "fail")})
            for name, (target, fn) in CORRUPTIONS.items():
                bad = dict(sp, fields=fn(sp["fields"]))
                if bad["fields"] == sp["fields"]: rows.append({"case": cid, "variant": name, "applicable": False}); continue
                r = evaluate(sp, render_card(bad))
                key = {"glyph_exact": "title", "required_fields": "fields"}[target]
                rows.append({"case": cid, "variant": name, "applicable": True, "detected": any(x["constraint_id"] == key and x["verdict"] == "fail" for x in r)})
            sw = dict(sp, fields=sp["fields"]); svg = render_card(sw).replace('y="60"', 'y="999"')
            r = evaluate(sp, svg); rows.append({"case": cid, "variant": "title_moved_last", "applicable": True, "detected": any(x["constraint_id"] == "order" and x["verdict"] == "fail" for x in r)})
        if "stages" in sp:
            st = sp["stages"]; rows.append({"case": cid, "variant": "clean", "should_fail": [], "failed": ["diagram"] if diagram_fidelity(st, mermaid(st))["verdict"] == "fail" else []})
            for name, kw in {"swap_order": {"swap": (1, 2)}, "drop_stage": {"drop": 3}, "invented_metric": {"add_metric": True}}.items():
                rows.append({"case": cid, "variant": name, "applicable": True, "detected": diagram_fidelity(st, mermaid(st, **kw))["verdict"] == "fail"})
    app = [r for r in rows if r.get("applicable")]; clean = [r for r in rows if r["variant"] == "clean"]
    by = defaultdict(Counter)
    for r in app: by[r["variant"]]["detected" if r["detected"] else "missed"] += 1
    det = sum(r["detected"] for r in app)
    return {"rows": rows, "detection": {"detected": det, "denominator": len(app), "value": round(det / len(app), 6) if app else None},
            "false_positives_on_clean": {"count": sum(bool(r["failed"]) for r in clean), "denominator": len(clean)},
            "by_variant": {k: dict(v) for k, v in sorted(by.items())},
            "limitations": ["corruptions are generated by the same author as the checks (self-consistency test, not an external benchmark)",
                            "artifacts are template SVG, not outputs of any generative model", "no human annotations exist; aesthetic axes unmeasured"]}
